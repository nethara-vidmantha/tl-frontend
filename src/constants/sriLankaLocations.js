/**
 * Search towns, districts, or provinces
 */
export const searchSriLankaLocations = (query = '') => {
  const q = query.trim().toLowerCase();
  if (!q) return [];

  const results = [];

  Object.keys(SRI_LANKA_HIERARCHY).forEach((province) => {
    const districts = SRI_LANKA_HIERARCHY[province];
    Object.keys(districts).forEach((district) => {
      const towns = districts[district];
      towns.forEach((town) => {
        if (
          town.toLowerCase().includes(q) ||
          district.toLowerCase().includes(q) ||
          province.toLowerCase().includes(q)
        ) {
          results.push({
            town,
            district,
            province,
            fullName: `${town}, ${district} (${province} Province)`
          });
        }
      });
    });
  });

  return results;
};
